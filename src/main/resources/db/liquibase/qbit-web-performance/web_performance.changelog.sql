-- Referential integrity (foreign keys), part 2: one changeset per foreign key, named
-- fk_<child table>_<column>. Each first records and repairs rows whose parent is
-- missing (a nullable column is set to NULL; a NOT NULL row is copied in full to
-- qqq_fk_quarantine and deleted, PostgreSQL only), then adds the constraint. Each
-- is marked ran when its constraint already exists (a host that added it itself).
-- ON DELETE: owned details CASCADE (findings and the report of a run,
-- comparisons of a site change); optional pointers SET NULL; tested pages and
-- budgets RESTRICT, because history is kept (D8): disable a page or budget instead
-- of deleting it.

